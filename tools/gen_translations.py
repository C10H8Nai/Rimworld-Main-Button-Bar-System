root = sys.argv[1]
keys = [t[0] for t in T]
assert len(keys) == len(set(keys)), "duplicate key"
for folder, col in folders.items():
    path = os.path.join(root, "Languages", folder, "Keyed", "MainButtonBarSystem.xml")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<LanguageData>\n')
        for t in T:
            f.write(f"  <{t[0]}>{escape(t[col])}</{t[0]}>\n")
        f.write("</LanguageData>\n")
print("\n".join(keys))
